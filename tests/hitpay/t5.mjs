// 退款（2026-11-01）：只有管理员能退、金额上限、HitPay 退款 API、失败后手动记录、不超退
import {call,addOrder,DB,HP,ENV} from "./harness.mjs";
let pass=0,fail=0; const ok=(c,m)=>{ console.log((c?"✅ ":"❌ ")+m); c?pass++:fail++; };
const paid=(ref,amt=40.30)=>{ const id=crypto.randomUUID(); HP.reqs[id]={id,status:"completed",amount:String(amt),reference_number:ref,payments:[{id:"pay-"+ref.toLowerCase()+"-1234",status:"succeeded",payment_type:"duitnow",fees:"0.48"}],url:"https://securecheckout.hit-pay.com/x"};
  return addOrder({ref,outlet:"OKR",order_type:"pickup",outlet_idx:0,customer_name:"测试",customer_phone:"0123456789",amount:amt,message:"x",status:"paid",pay_provider:"hitpay",pay_acct:"d",pay_id:id}); };
const adm={authorization:"Bearer eyadmin"}, mgr={authorization:"Bearer eymgr"};
let o=paid("MK1101-0001");
let r=await call({action:"refund",id:o.id,amount:10,reason:"少餐",mode:"hitpay"});
ok(r.status===400&&/登录/.test(r.body.error),"没登录 → 不能退款");
r=await call({action:"refund",id:o.id,amount:10,reason:"少餐",mode:"hitpay"},{authorization:"Bearer eystranger"});
ok(r.status===400&&/白名单/.test(r.body.error),"登录了但不在店员白名单 → 不能退款");
r=await call({action:"refund",id:o.id,amount:10,reason:"少餐",mode:"hitpay"},mgr);
ok(r.status===400&&/管理员/.test(r.body.error)&&!HP.refunds,"分店经理 → 不能退款，也没打到 HitPay");
r=await call({action:"refund",id:o.id,amount:10,reason:"",mode:"hitpay"},adm);
ok(r.status===400&&/原因/.test(r.body.error),"没填原因 → 拒绝");
r=await call({action:"refund",id:o.id,amount:0,reason:"少餐",mode:"hitpay"},adm);
ok(r.status===400&&/金额/.test(r.body.error),"金额 0 → 拒绝");
r=await call({action:"refund",id:o.id,amount:50,reason:"少餐",mode:"hitpay"},adm);
ok(r.status===400&&/最多还能退 RM 40\.30/.test(r.body.error)&&!HP.refunds,"超过订单金额 → 拒绝（不打 HitPay）");
r=await call({action:"refund",id:o.id,amount:10.5,reason:"漏单少餐",mode:"hitpay"},adm);
ok(r.status===200&&r.body.status==="done"&&HP.refunds.length===1&&HP.refunds[0].amount==="10.50"&&HP.refunds[0].payment_id==="pay-mk1101-0001-1234","部分退款 RM10.50 → HitPay 收到正确的 payment_id 和金额");
ok(DB.refunds.length===1&&DB.refunds[0].status==="done"&&DB.refunds[0].created_by==="a@x.com"&&/^rf-/.test(DB.refunds[0].hitpay_refund_id),"退款记录：done、记下是谁退的、HitPay 退款编号");
r=await call({action:"refund",id:o.id,amount:30,reason:"再退",mode:"hitpay"},adm);
ok(r.status===400&&/最多还能退 RM 29\.80/.test(r.body.error),"已退 10.50 → 最多还能退 29.80，不能超退");
r=await call({action:"refund",id:o.id,amount:29.8,reason:"全部退完",mode:"hitpay"},adm);
ok(r.status===200&&DB.refunds.filter(x=>x.status==="done").length===2,"把剩下的 29.80 退完");
// HitPay 拒绝（例如 DuitNow 不能退）→ 记录 failed，不算已退，可改手动
let o2=paid("MK1101-0002"); HP.refundFail="This payment method cannot be refunded"; HP.refunds=[];
r=await call({action:"refund",id:o2.id,amount:20,reason:"客人取消",mode:"hitpay"},adm);
ok(r.status===400&&/cannot be refunded/.test(r.body.error)&&/手动退款/.test(r.body.error),"HitPay 拒绝 → 把原因告诉管理员，并提示手动退款");
ok(DB.refunds.filter(x=>x.order_id===o2.id)[0].status==="failed","失败的退款记成 failed");
HP.refundFail=null; HP.refunds=[];
r=await call({action:"refund",id:o2.id,amount:20,reason:"已在网银手动转给客人",mode:"manual"},adm);
ok(r.status===200&&r.body.status==="manual"&&!HP.refunds.length,"改选「已手动退款」→ 只记录，不打 HitPay");
r=await call({action:"refund",id:o2.id,amount:20.3,reason:"剩下的",mode:"manual"},adm);
ok(r.status===200,"failed 那笔不占额度，手动那笔 20 + 再 20.30 = 40.30 刚好");
// 非已收款 / 不是 HitPay
let o3=addOrder({ref:"MK1101-0003",outlet:"OKR",order_type:"pickup",amount:30,message:"x",status:"pending"});
r=await call({action:"refund",id:o3.id,amount:5,reason:"测试",mode:"manual"},adm);
ok(r.status===400&&/已收款/.test(r.body.error),"还没付款的单 → 不能退款");
let o4=addOrder({ref:"MK1101-0004",outlet:"OKR",order_type:"pickup",amount:30,message:"x",status:"paid"});
r=await call({action:"refund",id:o4.id,amount:5,reason:"测试",mode:"hitpay"},adm);
ok(r.status===400&&/不是 HitPay/.test(r.body.error),"不是 HitPay 付款的单 → 不能用 HitPay 退款，只能手动记录");
r=await call({action:"refund",id:"abc",amount:5,reason:"测试",mode:"manual"},adm);
ok(r.status===400,"订单 id 不对 → 拒绝");
DB.noRefundTable=true; r=await call({action:"refund",id:o.id,amount:1,reason:"测试",mode:"manual"},adm);
ok(r.status===400&&/verify-refund\.sql/.test(r.body.error),"还没跑 verify-refund.sql → 提示去跑");
ok(!JSON.stringify(r.body).includes(ENV.WEB_HITPAY_API_KEY),"回传内容不含 API key");
console.log(`\n${pass} ✅ / ${fail} ❌`); process.exit(fail?1:0);
